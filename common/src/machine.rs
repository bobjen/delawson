//! Pinned machine keys over TLS 1.3 (RFC 7250 raw public keys).
//! Enrollment is trusted configuration, independent of the KS unlock secret.
use crate::{Context, Error, Result};
use rustls::{client::danger::*, pki_types::*, server::danger::*, sign::*, *};
use serde::Deserialize;
use std::{
    io::{self, Read, Write},
    net::TcpStream,
    path::PathBuf,
    sync::{Arc, Mutex},
    time::{Duration, Instant},
};

#[derive(Clone, Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Member {
    /// DER SubjectPublicKeyInfo, hex encoded. Never a private key.
    pub public_key: String,
    /// Process identities this physical machine may host.
    pub services: Vec<String>,
}
#[derive(Clone, Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Authentication {
    #[serde(default)]
    pub members: Vec<Member>,
    /// Local software PKCS#8 DER key, for development. Omit for anonymous operators.
    pub private_key: Option<PathBuf>,
    /// Local TPM primary unique-data file, generated by scripts/machine-identity.
    pub tpm_unique: Option<PathBuf>,
    pub public_key: Option<PathBuf>,
    #[serde(default = "device")]
    pub tpm_device: String,
    /// Optional owner-hierarchy authorization file, never passed as a literal secret.
    pub owner_auth: Option<PathBuf>,
}
fn device() -> String {
    "/dev/tpmrm0".into()
}
fn decode(text: &str) -> Result<Vec<u8>> {
    if text.len() % 2 != 0 || !text.is_ascii() {
        return Err(Error::new("invalid public key hex"));
    }
    (0..text.len())
        .step_by(2)
        .map(|i| {
            u8::from_str_radix(&text[i..i + 2], 16)
                .map_err(|_| Error::new("invalid public key hex"))
        })
        .collect()
}
impl Authentication {
    pub fn load_identity(&mut self, path: &std::path::Path) -> Result<()> {
        let mut local: Authentication =
            toml::from_str(&std::fs::read_to_string(path)?).context("machine identity file")?;
        if !local.members.is_empty() {
            return Err(Error::new("local identity file cannot change enrollment"));
        }
        let base = path.parent().unwrap_or(std::path::Path::new("."));
        for value in [
            &mut local.private_key,
            &mut local.public_key,
            &mut local.tpm_unique,
            &mut local.owner_auth,
        ] {
            if let Some(p) = value {
                if p.is_relative() {
                    *p = base.join(&*p);
                }
            }
        }
        self.private_key = local.private_key;
        self.public_key = local.public_key;
        self.tpm_unique = local.tpm_unique;
        self.tpm_device = local.tpm_device;
        self.owner_auth = local.owner_auth;
        Ok(())
    }

    pub fn permits(&self, key: Option<&[u8]>, service: &str) -> bool {
        key.is_some_and(|key| {
            self.members.iter().any(|m| {
                decode(&m.public_key).is_ok_and(|p| p == key)
                    && m.services.iter().any(|s| s.eq_ignore_ascii_case(service))
            })
        })
    }
    fn verifier(&self) -> Result<Arc<Pins>> {
        if self.members.is_empty() {
            return Err(Error::new("machine authentication needs enrolled keys"));
        }
        let mut members = Vec::new();
        for m in &self.members {
            members.push((decode(&m.public_key)?, m.services.clone()));
        }
        Ok(Arc::new(Pins { members }))
    }
    fn key(&self) -> Result<Option<Arc<CertifiedKey>>> {
        if self.private_key.is_some() && self.tpm_unique.is_some() {
            return Err(Error::new("choose software or TPM identity"));
        }
        let key: Arc<dyn SigningKey> = if let Some(path) = &self.private_key {
            let der = PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(std::fs::read(path)?));
            rustls::crypto::ring::sign::any_supported_type(&der).context("loading machine key")?
        } else if self.tpm_unique.is_some() {
            Arc::new(TpmKey { config: self.clone() })
        } else {
            return Ok(None);
        };
        let public = if let Some(path) = &self.public_key {
            std::fs::read(path)?
        } else {
            key.public_key()
                .ok_or_else(|| Error::new("machine public key required"))?
                .as_ref()
                .to_vec()
        };
        // For software identities catch a mismatched public file before listening.
        if let Some(actual) = key.public_key() {
            if actual.as_ref() != public {
                return Err(Error::new("machine public/private key mismatch"));
            }
        }
        if !self.members.iter().any(|m| decode(&m.public_key).is_ok_and(|p| p == public)) {
            return Err(Error::new("local machine key is not enrolled"));
        }
        Ok(Some(Arc::new(CertifiedKey::new(vec![CertificateDer::from(public)], key))))
    }
}

#[derive(Debug)]
struct Pins {
    members: Vec<(Vec<u8>, Vec<String>)>,
}
fn denied() -> rustls::Error {
    rustls::Error::General("machine key is not enrolled for the requested service".into())
}
fn signature(
    message: &[u8],
    cert: &CertificateDer<'_>,
    dss: &DigitallySignedStruct,
) -> std::result::Result<HandshakeSignatureValid, rustls::Error> {
    rustls::crypto::verify_tls13_signature_with_raw_key(
        message,
        &SubjectPublicKeyInfoDer::from(cert.as_ref()),
        dss,
        &rustls::crypto::ring::default_provider().signature_verification_algorithms,
    )
}
impl ServerCertVerifier for Pins {
    fn verify_server_cert(
        &self,
        cert: &CertificateDer<'_>,
        intermediates: &[CertificateDer<'_>],
        name: &ServerName<'_>,
        _: &[u8],
        _: UnixTime,
    ) -> std::result::Result<ServerCertVerified, rustls::Error> {
        let ServerName::DnsName(name) = name else {
            return Err(denied());
        };
        if intermediates.is_empty()
            && self.members.iter().any(|(p, services)| {
                p == cert.as_ref() && services.iter().any(|s| s.eq_ignore_ascii_case(name.as_ref()))
            })
        {
            Ok(ServerCertVerified::assertion())
        } else {
            Err(denied())
        }
    }
    fn verify_tls12_signature(
        &self,
        _: &[u8],
        _: &CertificateDer<'_>,
        _: &DigitallySignedStruct,
    ) -> std::result::Result<HandshakeSignatureValid, rustls::Error> {
        Err(denied())
    }
    fn verify_tls13_signature(
        &self,
        m: &[u8],
        c: &CertificateDer<'_>,
        d: &DigitallySignedStruct,
    ) -> std::result::Result<HandshakeSignatureValid, rustls::Error> {
        signature(m, c, d)
    }
    fn supported_verify_schemes(&self) -> Vec<SignatureScheme> {
        rustls::crypto::ring::default_provider()
            .signature_verification_algorithms
            .supported_schemes()
    }
    fn requires_raw_public_keys(&self) -> bool {
        true
    }
}
impl ClientCertVerifier for Pins {
    // Anonymous operators may unlock. Registration and key issuance check the
    // authenticated identity separately; no user authentication is implied.
    fn client_auth_mandatory(&self) -> bool {
        false
    }
    fn root_hint_subjects(&self) -> &[DistinguishedName] {
        &[]
    }
    fn verify_client_cert(
        &self,
        c: &CertificateDer<'_>,
        chain: &[CertificateDer<'_>],
        _: UnixTime,
    ) -> std::result::Result<ClientCertVerified, rustls::Error> {
        if chain.is_empty() && self.members.iter().any(|(p, _)| p == c.as_ref()) {
            Ok(ClientCertVerified::assertion())
        } else {
            Err(denied())
        }
    }
    fn verify_tls12_signature(
        &self,
        _: &[u8],
        _: &CertificateDer<'_>,
        _: &DigitallySignedStruct,
    ) -> std::result::Result<HandshakeSignatureValid, rustls::Error> {
        Err(denied())
    }
    fn verify_tls13_signature(
        &self,
        m: &[u8],
        c: &CertificateDer<'_>,
        d: &DigitallySignedStruct,
    ) -> std::result::Result<HandshakeSignatureValid, rustls::Error> {
        signature(m, c, d)
    }
    fn supported_verify_schemes(&self) -> Vec<SignatureScheme> {
        ServerCertVerifier::supported_verify_schemes(self)
    }
    fn requires_raw_public_keys(&self) -> bool {
        true
    }
}
#[derive(Debug)]
struct Anonymous;
impl rustls::client::ResolvesClientCert for Anonymous {
    fn resolve(&self, _: &[&[u8]], _: &[SignatureScheme]) -> Option<Arc<CertifiedKey>> {
        None
    }
    fn has_certs(&self) -> bool {
        false
    }
    fn only_raw_public_keys(&self) -> bool {
        true
    }
}

#[derive(Clone, Debug)]
struct TpmKey {
    config: Authentication,
}
impl SigningKey for TpmKey {
    fn choose_scheme(&self, offered: &[SignatureScheme]) -> Option<Box<dyn Signer>> {
        offered
            .contains(&SignatureScheme::RSA_PSS_SHA256)
            .then(|| Box::new(self.clone()) as Box<dyn Signer>)
    }
    fn algorithm(&self) -> SignatureAlgorithm {
        SignatureAlgorithm::RSA
    }
}
fn command(program: &str, args: &[&str]) -> Result<()> {
    let output = tempfile::tempfile()?;
    let errors = tempfile::tempfile()?;
    let mut child = std::process::Command::new(program)
        .args(args)
        .stdout(output)
        .stderr(errors.try_clone()?)
        .spawn()?;
    let start = Instant::now();
    loop {
        if let Some(status) = child.try_wait()? {
            if status.success() {
                return Ok(());
            }
            let mut reason = String::new();
            use std::io::{Seek, SeekFrom};
            let mut errors = errors;
            errors.seek(SeekFrom::Start(0))?;
            errors.take(4096).read_to_string(&mut reason)?;
            return Err(Error::new(format!("{program} failed: {reason}")));
        }
        if start.elapsed() > Duration::from_secs(20) {
            let _ = child.kill();
            let _ = child.wait();
            return Err(Error::new(format!("{program} timed out")));
        }
        std::thread::sleep(Duration::from_millis(5));
    }
}
impl Signer for TpmKey {
    fn sign(&self, message: &[u8]) -> std::result::Result<Vec<u8>, rustls::Error> {
        let perform = || -> Result<Vec<u8>> {
            if !self.config.tpm_device.starts_with("/dev/tpmrm") {
                return Err(Error::new("TPM signing requires a resource-manager device"));
            }
            let temp = tempfile::tempdir()?;
            let context = temp.path().join("key.ctx");
            let input = temp.path().join("message");
            let output = temp.path().join("signature");
            let public = temp.path().join("public.der");
            std::fs::write(&input, message)?;
            let tcti = format!("device:{}", self.config.tpm_device);
            let unique = self.config.tpm_unique.as_ref().expect("TPM unique");
            let mut args = vec![
                "-T",
                &tcti,
                "-C",
                "o",
                "-G",
                "rsa2048:rsapss-sha256:null",
                "-g",
                "sha256",
                "-a",
                "fixedtpm|fixedparent|sensitivedataorigin|userwithauth|sign|noda",
                "-u",
                unique.to_str().ok_or_else(|| Error::new("non-UTF8 TPM path"))?,
                "-c",
                context.to_str().unwrap(),
                "-f",
                "der",
                "-o",
                public.to_str().unwrap(),
            ];
            let auth = self.config.owner_auth.as_ref().map(|p| format!("file:{}", p.display()));
            if let Some(auth) = &auth {
                args.extend(["-P", auth.as_str()]);
            }
            command("tpm2_createprimary", &args)?;
            let expected = std::fs::read(
                self.config
                    .public_key
                    .as_ref()
                    .ok_or_else(|| Error::new("TPM public key required"))?,
            )?;
            if std::fs::read(public)? != expected {
                return Err(Error::new("TPM identity changed; refusing to sign"));
            }
            command(
                "tpm2_sign",
                &[
                    "-T",
                    &tcti,
                    "-c",
                    context.to_str().unwrap(),
                    "-g",
                    "sha256",
                    "-s",
                    "rsapss",
                    "-f",
                    "plain",
                    "-o",
                    output.to_str().unwrap(),
                    input.to_str().unwrap(),
                ],
            )?;
            Ok(std::fs::read(output)?)
        };
        perform().map_err(|e| rustls::Error::General(e.to_string()))
    }
    fn scheme(&self) -> SignatureScheme {
        SignatureScheme::RSA_PSS_SHA256
    }
}

/// TLS record processing is serialized, but socket reads happen outside that
/// lock: a waiting reader must never prevent a writer from sending a request.
pub struct Stream {
    socket: TcpStream,
    tls: Option<Arc<Mutex<Connection>>>,
    sending: Option<Arc<Mutex<()>>>,
    pub peer_key: Option<Vec<u8>>,
}
impl Stream {
    pub fn new(
        mut socket: TcpStream,
        config: &crate::config::Messaging,
        server: bool,
    ) -> Result<Self> {
        let Some(auth) = &config.authentication else {
            return Ok(Self { socket, tls: None, sending: None, peer_key: None });
        };
        let old_read = socket.read_timeout()?;
        let old_write = socket.write_timeout()?;
        socket.set_read_timeout(Some(Duration::from_secs(30)))?;
        socket.set_write_timeout(Some(Duration::from_secs(30)))?;
        let provider = Arc::new(rustls::crypto::ring::default_provider());
        let pins = auth.verifier()?;
        let key = auth.key()?;
        let mut conn = if server {
            let key = key.ok_or_else(|| Error::new("server requires a machine identity"))?;
            let mut c = ServerConfig::builder_with_provider(provider)
                .with_protocol_versions(&[&version::TLS13])
                .context("TLS versions")?
                .with_client_cert_verifier(pins)
                .with_cert_resolver(Arc::new(
                    rustls::server::AlwaysResolvesServerRawPublicKeys::new(key),
                ));
            c.send_tls13_tickets = 0;
            c.alpn_protocols = vec![b"delawson/1".to_vec()];
            Connection::Server(ServerConnection::new(Arc::new(c)).context("TLS server")?)
        } else {
            let resolver: Arc<dyn rustls::client::ResolvesClientCert> = match key {
                Some(key) => Arc::new(rustls::client::AlwaysResolvesClientRawPublicKeys::new(key)),
                None => Arc::new(Anonymous),
            };
            let mut c = ClientConfig::builder_with_provider(provider)
                .with_protocol_versions(&[&version::TLS13])
                .context("TLS versions")?
                .dangerous()
                .with_custom_certificate_verifier(pins)
                .with_client_cert_resolver(resolver);
            c.resumption = rustls::client::Resumption::disabled();
            c.alpn_protocols = vec![b"delawson/1".to_vec()];
            let expected = config.expected_peer.as_ref().ok_or_else(|| {
                Error::new("authenticated connection requires expected peer identity")
            })?;
            let name =
                ServerName::try_from(expected.to_ascii_lowercase()).context("peer identity")?;
            Connection::Client(ClientConnection::new(Arc::new(c), name).context("TLS client")?)
        };
        while conn.is_handshaking() {
            conn.complete_io(&mut socket).context("machine TLS handshake")?;
        }
        if conn.alpn_protocol() != Some(b"delawson/1") {
            return Err(Error::new("wrong machine protocol"));
        }
        let peer_key =
            conn.peer_certificates().and_then(|c| c.first()).map(|c| c.as_ref().to_vec());
        socket.set_read_timeout(old_read)?;
        socket.set_write_timeout(old_write)?;
        Ok(Self {
            socket,
            tls: Some(Arc::new(Mutex::new(conn))),
            sending: Some(Arc::new(Mutex::new(()))),
            peer_key,
        })
    }
    pub fn try_clone(&self) -> io::Result<Self> {
        Ok(Self {
            socket: self.socket.try_clone()?,
            tls: self.tls.clone(),
            sending: self.sending.clone(),
            peer_key: self.peer_key.clone(),
        })
    }
}
impl Read for Stream {
    fn read(&mut self, out: &mut [u8]) -> io::Result<usize> {
        let Some(tls) = &self.tls else {
            return self.socket.read(out);
        };
        if out.is_empty() {
            return Ok(0);
        }
        loop {
            {
                let mut conn = tls.lock().unwrap();
                match conn.reader().read(out) {
                    Err(e) if e.kind() == io::ErrorKind::WouldBlock => {}
                    result => return result,
                }
            }
            let mut buffer = [0; 16384];
            let count = self.socket.read(&mut buffer)?;
            if count == 0 {
                return Err(io::Error::new(
                    io::ErrorKind::UnexpectedEof,
                    "TLS connection ended without close notification",
                ));
            }
            let mut bytes = io::Cursor::new(&buffer[..count]);
            let mut conn = tls.lock().unwrap();
            while bytes.position() < count as u64 {
                if conn.read_tls(&mut bytes)? == 0 {
                    return Err(io::Error::new(
                        io::ErrorKind::InvalidData,
                        "TLS input made no progress",
                    ));
                }
                conn.process_new_packets()
                    .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e))?;
            }
            // KeyUpdate responses remain queued until the next application write,
            // as TLS 1.3 permits. Never wait for socket output while holding the
            // connection lock: both peers may be sending simultaneously.
        }
    }
}
impl Write for Stream {
    fn write(&mut self, input: &[u8]) -> io::Result<usize> {
        let Some(tls) = &self.tls else {
            return self.socket.write(input);
        };
        let _sending = self.sending.as_ref().unwrap().lock().unwrap();
        let mut encrypted = Vec::new();
        let written = {
            let mut conn = tls.lock().unwrap();
            let written = conn.writer().write(input)?;
            while conn.wants_write() {
                conn.write_tls(&mut encrypted)?;
            }
            written
        };
        // Preserve record order across writers while allowing the independent
        // reader to decrypt input even when this write blocks on a full socket.
        self.socket.write_all(&encrypted)?;
        Ok(written)
    }
    fn flush(&mut self) -> io::Result<()> {
        self.socket.flush()
    }
}
